"""Files written into a job directory, and the slurm command that runs them.

For every job:
  <phase>.<sub>.cmd   one bash script per step, holding exactly that step's command
  run.sh              runs the .cmd files in order, logs each to <phase>.<sub>.log,
                      stops at the first failure and records the result in dv_flow.status
"""

import shlex

from .constants import STATUS_FILE, TEST_STATUS_FILE


def _write_executable(path, lines):
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")  # LF even on Windows
    try:
        path.chmod(0o755)
    except OSError:
        pass


def write_cmd_files(job):
    """One <phase>.<sub>.cmd per step; `bash sim.phase.cmd` re-runs just that step."""
    job.directory.mkdir(parents=True, exist_ok=True)
    for st in job.steps:
        _write_executable(job.directory / st.cmd_file, [
            "#!/usr/bin/env bash",
            f"# dv_flow job: {job.name}  step: {st.tag}",
            f"cd {shlex.quote(job.directory.as_posix())} || exit 1",
            st.cmd,
        ])


def write_job_files(job):
    """Files a phase declares under `files:` (e.g. the wave dump script waves.tcl)."""
    job.directory.mkdir(parents=True, exist_ok=True)
    for name, content in job.files.items():
        (job.directory / name).write_text(content if content.endswith("\n") else content + "\n",
                                          encoding="utf-8", newline="\n")


def write_script(job):
    """Write the phase files, the .cmd files and run.sh (what slurm runs; also usable by hand)."""
    write_job_files(job)
    write_cmd_files(job)
    for stale in (STATUS_FILE, TEST_STATUS_FILE):   # results of an earlier run in this directory
        (job.directory / stale).unlink(missing_ok=True)
    q = shlex.quote
    lines = [
        "#!/usr/bin/env bash",
        f"# Generated by dv_flow.py - job: {job.name}",
        f"# model: {job.model}  phases: {','.join(job.phases)}"
        + (f"  test: {job.test['name']} ({job.test['testname']})  seed: {job.seed}" if job.kind == "test" else ""),
        "set -o pipefail",
        f"cd {q(job.directory.as_posix())} || exit 1",
        f"echo RUNNING > {STATUS_FILE}",
        # Slurm sends SIGTERM (scancel, time limit, preemption) before SIGKILL: record it.
        # A job that is SIGKILLed outright leaves RUNNING behind; the tracker then asks slurm.
        "step=start",
        f"trap 'echo \"FAIL $step killed by SIGTERM (scancel / time limit / preemption)\" > {STATUS_FILE}; "
        "exit 143' TERM",
        f"trap 'echo \"FAIL $step killed by SIGINT\" > {STATUS_FILE}; exit 130' INT",
        # sig 137 -> " (signal KILL)"
        'sig() { if [ "$1" -gt 128 ]; then echo " (signal $(kill -l $(($1 - 128))))"; fi; }',
        "",
    ]
    for i, st in enumerate(job.steps):
        rest = " ".join(s.tag for s in job.steps[i + 1:]) or "none"
        lines += [
            f"step={st.tag}",
            f"echo '=== [{st.tag}] {st.cmd.replace(chr(39), chr(39) + chr(92) + chr(39) + chr(39))}'",
            f"bash {q(st.cmd_file)} 2>&1 | tee {q(st.tag + '.log')}",
            "rc=${PIPESTATUS[0]}",                        # exit code of the step, not of tee
            f"if [ $rc -ne 0 ]; then echo '*** [{st.tag}] FAILED (rc='$rc'), skipped: {rest}'; "
            f'echo "FAIL {st.tag} rc=$rc$(sig $rc)" > {STATUS_FILE}; exit $rc; fi',
        ]
        if st.fail_patterns:                              # e.g. compile: "error-" in the log fails the step
            pats = " ".join(f"-e {q(x)}" for x in st.fail_patterns)
            lines += [
                f"hit=$(grep -Ein -m1 {pats} {q(st.tag + '.log')})",
                f'if [ -n "$hit" ]; then echo "*** [{st.tag}] FAILED (error in log, line $hit), '
                f'skipped: {rest}"; echo "FAIL {st.tag} error in log" > {STATUS_FILE}; exit 1; fi',
            ]
        lines.append("")
    lines += [f"echo PASS > {STATUS_FILE}", f"echo '=== job {job.name} PASSED'"]
    job.directory.mkdir(parents=True, exist_ok=True)
    _write_executable(job.script, lines)


def slurm_command(job):
    """The sbatch (batch) or srun (interactive) command line for a job, as a list."""
    s = job.slurm
    mode = s["mode"]
    sub = s[mode]
    cmd = [*shlex.split(sub["cmd"]), *sub.get("options", []), "-J", job.name,
           f"--chdir={job.directory.as_posix()}"]
    if s.get("partition"):
        cmd.append(f"--partition={s['partition']}")
    if job.timeout:
        cmd.append(f"--time={job.timeout}")          # slurm kills the job after this
    options = [str(o) for o in s.get("options") or []]
    if s.get("mem"):
        # slurm.mem / slurm_mem / --slurm-mem replace any --mem written in the options
        options = [o for o in options if not o.startswith(("--mem=", "--mem-per-cpu="))]
        cmd.append(f"--mem={s['mem']}")
    cmd += options
    if s.get("gui"):
        cmd += [str(o) for o in s.get("gui_options", [])]
    if mode == "batch":
        cmd.append(f"--output={(job.directory / 'slurm_%j.log').as_posix()}")
        dep = job.depends_on
        if dep is not None and dep.slurm["enable"] and dep.steps:
            # test jobs wait for the build; if the build fails slurm cancels them
            cmd += [f"--dependency=afterok:{dep.slurm_id or '<build-job-id>'}", "--kill-on-invalid-dep=yes"]
    cmd += ["bash", job.script.as_posix()] if mode == "interactive" else [job.script.as_posix()]
    return cmd
