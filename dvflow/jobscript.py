"""Files written into a job directory, and the slurm command that runs them.

Every job directory gets two equivalent sets of scripts:

  <phase>.csh   tcsh script per phase: its pre_phase, phase and post_phase commands
  <phase>.sh    the same in POSIX sh
  run.csh       runs the <phase>.csh scripts in order; records the result in dv_flow.status
  run.sh        the same with the <phase>.sh scripts

A phase script runs its steps in order, writes each step's output to
<phase>.<sub>.log, checks the phase's fail_patterns in it, and stops at the first
failing step (writing "FAIL <step> ..." to dv_flow.status). Each phase script also
works on its own: `tcsh -f compile.csh` or `sh compile.sh` re-runs just that phase.
The job's shell (`job_shell`, --shell) decides which set dv_flow and slurm run.
"""

import shlex

from .constants import STATUS_FILE, TEST_STATUS_FILE

# Signal names for exit codes above 128 (Linux numbering), indexed from 1 in csh.
_SIGNALS = "HUP INT QUIT ILL TRAP ABRT BUS FPE KILL USR1 SEGV USR2 PIPE ALRM TERM"
# Terminator of the quoted here-documents that print commands without any substitution.
_EOF = "DV_FLOW_EOF"

q = shlex.quote


def _write_executable(path, lines):
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")  # LF even on Windows
    try:
        path.chmod(0o755)
    except OSError:
        pass


def _print_literal(text, csh=False):
    """Lines that print `text` exactly as written (a quoted here-document, so nothing is
    substituted). csh ends it at a line identical to the word as typed, quotes included."""
    return [f"cat <<'{_EOF}'", text, f"'{_EOF}'" if csh else _EOF]


def _csh_bin(job):
    return "csh" if job.shell == "csh" else "tcsh"


def _rest(job, step):
    """Steps of the job after `step`, for the 'skipped:' message."""
    after = job.steps[job.steps.index(step) + 1:]
    return " ".join(s.tag for s in after) or "none"


def _header(job, shebang, phase=None, steps=()):
    what = f"phase: {phase} ({', '.join(s.sub for s in steps)})" if phase else f"phases: {','.join(job.phases)}"
    lines = [shebang, f"# Generated by dv_flow.py - job: {job.name}", f"# model: {job.model}  {what}"]
    if job.kind == "test":
        lines.append(f"# test: {job.test['name']} ({job.test['testname']})  seed: {job.seed}")
    return lines


# ------------------------------------------------------------------- tcsh
def csh_phase_script(job, phase, steps):
    """<phase>.csh: the phase's steps in order, stop at the first failure."""
    lines = _header(job, f"#!/bin/{_csh_bin(job)} -f", phase, steps) + [
        "# Each step runs as  ( <command> ; echo $status > <step>.rc ) |& tee <step>.log",
        "# so its exit code is kept although the output goes through tee.",
        "set nonomatch                      # unmatched [..] / * are passed on as typed",
        f"cd {q(job.directory.as_posix())}",
        f"set signames = ({_SIGNALS})",
    ]
    for st in steps:
        rc, log, hit, rest = q(st.tag + ".rc"), q(st.tag + ".log"), q(st.tag + ".hit"), _rest(job, st)
        lines += ["", f"# ---- {st.tag}", *_print_literal(f"=== [{st.tag}] {st.cmd}", csh=True),
                  f"rm -f {rc}",
                  f"( {st.cmd} ; echo $status > {rc} ) |& tee {log}",
                  "set rc = 1",
                  f"if ( -e {rc} ) set rc = `cat {rc}`",
                  f"rm -f {rc}",
                  'if ( "$rc" == "" ) set rc = 1',
                  "if ( $rc < 0 ) @ rc = $rc + 256          # some csh report signals as negative",
                  "if ( $rc != 0 ) then",
                  '  set sig = ""',
                  "  if ( $rc > 128 ) then                  # 139 -> (signal SEGV)",
                  "    @ n = $rc - 128",
                  '    if ( $n <= $#signames ) set sig = " (signal $signames[$n])"',
                  "  endif",
                  f'  echo "*** [{st.tag}] FAILED (rc=$rc$sig), skipped: {rest}"',
                  f'  echo "FAIL {st.tag} rc=$rc$sig" > {STATUS_FILE}',
                  "  exit $rc",
                  "endif"]
        if st.fail_patterns:                              # e.g. compile: "error-" in the log fails the step
            pats = " ".join(f"-e {q(x)}" for x in st.fail_patterns)
            lines += [f"grep -Ein -m1 {pats} {log} > {hit}",
                      f"if ( ! -z {hit} ) then",
                      f'  echo -n "FAIL {st.tag} error in log, line " > {STATUS_FILE}',
                      f"  cat {hit} >> {STATUS_FILE}",
                      f"  rm -f {hit}",
                      f'  echo "*** [{st.tag}] FAILED (error in log), skipped: {rest}"',
                      f"  cat {STATUS_FILE}",
                      "  exit 1",
                      "endif",
                      f"rm -f {hit}"]
    return lines + ["", "exit 0"]


def csh_run_script(job):
    """run.csh: every <phase>.csh in order; PASS / FAIL in dv_flow.status."""
    sh = _csh_bin(job)
    lines = _header(job, f"#!/bin/{sh} -f") + [
        f"cd {q(job.directory.as_posix())}",
        f"echo RUNNING > {STATUS_FILE}",
        "set step = start",
        # Ctrl-C (SIGINT) is recorded. csh cannot trap SIGTERM (scancel, time limit):
        # the status file then stays RUNNING and the tracker asks slurm (sacct) why.
        "onintr interrupted",
    ]
    for phase, _ in job.phase_groups():
        lines += ["", f"set step = {phase}", f"{sh} -f {q(phase + '.csh')}", "set rc = $status",
                  "if ( $rc != 0 ) goto failed"]
    return lines + [
        "", f"echo PASS > {STATUS_FILE}", *_print_literal(f"=== job {job.name} PASSED", csh=True), "exit 0",
        "", "failed:                            # the phase script wrote FAIL, unless it was killed",
        "if ( $rc < 0 ) @ rc = $rc + 256",
        # (if/endif: a one-line `if (..) echo .. > file` empties the file even when false)
        f'if ( "`cat {STATUS_FILE}`" == "RUNNING" ) then',
        f'  echo "FAIL $step rc=$rc" > {STATUS_FILE}',
        "endif",
        "exit $rc",
        "", "interrupted:",
        f'echo "FAIL $step killed by SIGINT" > {STATUS_FILE}',
        "exit 130",
    ]


# ------------------------------------------------------------------- sh
def sh_phase_script(job, phase, steps):
    """<phase>.sh: the phase's steps in order, stop at the first failure."""
    lines = _header(job, "#!/bin/sh", phase, steps) + [
        "# Each step runs in a subshell that saves its exit code to <step>.rc;",
        "# the output goes through tee to <step>.log.",
        f"cd {q(job.directory.as_posix())} || exit 1",
        '# sig 139 -> " (signal SEGV)"',
        'sig() { if [ "$1" -gt 128 ]; then echo " (signal $(kill -l $(($1 - 128)) 2>/dev/null))"; fi; }',
    ]
    for st in steps:
        rc, log, rest = q(st.tag + ".rc"), q(st.tag + ".log"), _rest(job, st)
        lines += ["", f"# ---- {st.tag}", *_print_literal(f"=== [{st.tag}] {st.cmd}"),
                  f"rm -f {rc}",
                  "(",
                  st.cmd,
                  f"echo $? > {rc}",
                  f") 2>&1 | tee {log}",
                  f'rc=$(cat {rc} 2>/dev/null); rm -f {rc}; [ -n "$rc" ] || rc=1',
                  'if [ "$rc" -ne 0 ]; then',
                  '  s=$(sig "$rc")',
                  f'  echo "*** [{st.tag}] FAILED (rc=$rc$s), skipped: {rest}"',
                  f'  echo "FAIL {st.tag} rc=$rc$s" > {STATUS_FILE}',
                  '  exit "$rc"',
                  "fi"]
        if st.fail_patterns:
            pats = " ".join(f"-e {q(x)}" for x in st.fail_patterns)
            lines += [f"hit=$(grep -Ein -m1 {pats} {log})",
                      'if [ -n "$hit" ]; then',
                      f'  echo "FAIL {st.tag} error in log, line $hit" > {STATUS_FILE}',
                      f'  echo "*** [{st.tag}] FAILED (error in log, line $hit), skipped: {rest}"',
                      "  exit 1",
                      "fi"]
    return lines + ["", "exit 0"]


def sh_run_script(job):
    """run.sh: every <phase>.sh in order; PASS / FAIL in dv_flow.status."""
    lines = _header(job, "#!/bin/sh") + [
        f"cd {q(job.directory.as_posix())} || exit 1",
        f"echo RUNNING > {STATUS_FILE}",
        "step=start",
        # Slurm sends SIGTERM (scancel, time limit, preemption) before SIGKILL: record it.
        f"trap 'echo \"FAIL $step killed by SIGTERM (scancel / time limit / preemption)\" > {STATUS_FILE}; "
        "exit 143' TERM",
        f"trap 'echo \"FAIL $step killed by SIGINT\" > {STATUS_FILE}; exit 130' INT",
        "failed() {   # the phase script wrote FAIL, unless it was killed",
        f'  [ "$(cat {STATUS_FILE})" = RUNNING ] && echo "FAIL $step rc=$1" > {STATUS_FILE}',
        '  exit "$1"',
        "}",
    ]
    for phase, _ in job.phase_groups():
        lines += ["", f"step={phase}", f"sh {q(phase + '.sh')} || failed $?"]
    return lines + ["", f"echo PASS > {STATUS_FILE}", *_print_literal(f"=== job {job.name} PASSED"), "exit 0"]


# ------------------------------------------------------------------- all files
def write_job_files(job):
    """Files a phase declares under `files:` (e.g. the wave dump script waves.tcl)."""
    job.directory.mkdir(parents=True, exist_ok=True)
    for name, content in job.files.items():
        (job.directory / name).write_text(content if content.endswith("\n") else content + "\n",
                                          encoding="utf-8", newline="\n")


def write_script(job):
    """Write the phase files and both script sets (.csh and .sh) into the job directory."""
    write_job_files(job)
    for stale in (STATUS_FILE, TEST_STATUS_FILE):   # results of an earlier run in this directory
        (job.directory / stale).unlink(missing_ok=True)
    d = job.directory
    for phase, steps in job.phase_groups():
        _write_executable(d / f"{phase}.csh", csh_phase_script(job, phase, steps))
        _write_executable(d / f"{phase}.sh", sh_phase_script(job, phase, steps))
    _write_executable(d / "run.csh", csh_run_script(job))
    _write_executable(d / "run.sh", sh_run_script(job))


def script_command(job, script):
    """How to run one of the job's scripts with its shell: [tcsh, -f, x.csh] or [sh, x.sh]."""
    return ["sh", str(script)] if job.ext == "sh" else [_csh_bin(job), "-f", str(script)]


def slurm_command(job):
    """The sbatch (batch) or srun (interactive) command line for a job, as a list."""
    s = job.slurm
    mode = s["mode"]
    sub = s[mode]
    cmd = [*shlex.split(sub["cmd"]), *sub.get("options", []), "-J", job.name,
           f"--chdir={job.directory.as_posix()}"]
    if s.get("partition"):
        cmd.append(f"--partition={s['partition']}")
    if job.timeout:
        cmd.append(f"--time={job.timeout}")          # slurm kills the job after this
    options = [str(o) for o in s.get("options") or []]
    if s.get("mem"):
        # slurm.mem / slurm_mem / --slurm-mem replace any --mem written in the options
        options = [o for o in options if not o.startswith(("--mem=", "--mem-per-cpu="))]
        cmd.append(f"--mem={s['mem']}")
    cmd += options
    if s.get("gui"):
        cmd += [str(o) for o in s.get("gui_options", [])]
    if mode == "batch":
        cmd.append(f"--output={(job.directory / 'slurm_%j.log').as_posix()}")
        dep = job.depends_on
        if dep is not None and dep.slurm["enable"] and dep.steps:
            # test jobs wait for the build; if the build fails slurm cancels them
            cmd += [f"--dependency=afterok:{dep.slurm_id or '<build-job-id>'}", "--kill-on-invalid-dep=yes"]
    # sbatch runs the script by its #! line; srun is given the shell explicitly
    cmd += script_command(job, job.script.as_posix()) if mode == "interactive" else [job.script.as_posix()]
    return cmd
